import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { startLocalEditor } from '../scripts/local-editor.mjs';

test('local editor: preview, disk save, newer typing, reload, failure, article and history', {timeout:120000}, async () => {
  const directory=await mkdtemp(path.join(tmpdir(),'roof-editor-browser-'));
  let service,browser;
  try {
    service=await startLocalEditor({port:0,directory});
    browser=await chromium.launch({channel:'msedge',headless:true});
    const page=await browser.newPage({viewport:{width:1600,height:1000}});
    const errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.goto(service.origin+'/__editor/',{waitUntil:'networkidle'});
    assert.equal((await page.request.post(service.origin+'/__editor/api/save',{data:{revision:0,entries:{},articles:[]}})).status(),403);
    assert.equal((await page.request.get(service.origin+'/.local-editor/catalog.json')).status(),404);
    await page.frameLocator('#pagePreview').locator('main h1').waitFor();
    assert.match(await page.frameLocator('#pagePreview').locator('main h1').textContent(),/屋顶维修/);
    assert.equal(await page.frameLocator('#pagePreview').locator('a.phoneAction').getAttribute('href'),'tel:0405878406');
    assert.equal(await page.frameLocator('#pagePreview').locator('a[href^="/__editor"], .adminBtn').count(),0);
    await page.frameLocator('#pagePreview').locator('main h1').click();
    await page.locator('#chineseCopy').fill('本地检查用中文标题');
    let release, arrived;
    const entered=new Promise(resolve=>{arrived=resolve;});const gate=new Promise(resolve=>{release=resolve;});
    await page.route('**/__editor/api/save',async route=>{arrived();await gate;await route.continue();},{times:1});
    await page.locator('#saveButton').click();await entered;
    await page.locator('#chineseCopy').fill('保存过程中继续输入的标题');
    release();
    await page.locator('#saveButton:not(:disabled)').waitFor();
    assert.equal(await page.locator('#chineseCopy').inputValue(),'保存过程中继续输入的标题');
    assert.match(await page.locator('#saveState').textContent(),/未保存/);
    await page.locator('#saveButton').click();
    await page.locator('#saveState').filter({hasText:'版本 2'}).waitFor();
    assert.equal(Object.values(JSON.parse(await readFile(path.join(directory,'draft.json'),'utf8')).entries)[0].zh,'保存过程中继续输入的标题');
    await page.reload({waitUntil:'networkidle'});
    await page.frameLocator('#pagePreview').locator('main h1').filter({hasText:'保存过程中继续输入的标题'}).waitFor();
    await page.locator('#previewEnglish').click();
    await page.frameLocator('#pagePreview').locator('main h1').filter({hasText:'Roof Repairs Canberra'}).waitFor();
    await page.locator('#previewChinese').click();
    await page.frameLocator('#pagePreview').locator('main h1').click();
    await page.locator('#chineseCopy').fill('连接失败后仍保留');
    await page.route('**/__editor/api/save',route=>route.abort(),{times:1});
    await page.locator('#saveButton').click();await page.locator('#editorError').filter({hasText:'无法连接'}).waitFor();
    assert.equal(await page.locator('#chineseCopy').inputValue(),'连接失败后仍保留');
    await page.locator('#saveButton').click();await page.locator('#saveState').filter({hasText:'版本 3'}).waitFor();
    await page.locator('#newArticle').click();await page.locator('#articleName').fill('未保存文章');await page.locator('#closeArticle').click();
    await page.locator('#articleDiscardDialog[open]').waitFor();await page.locator('#keepArticle').click();
    assert.equal(await page.locator('#articleName').inputValue(),'未保存文章');
    await page.locator('#articleSlug').fill('local-browser-test-article');await page.locator('#articleName').fill('暴风雨后如何记录屋顶漏水');
    await page.locator('#articleSummary').fill('用于测试本地文章保存和预览的完整摘要。');await page.locator('#articleLead').fill('从安全位置观察可见迹象，并记录天气和发生时间。');
    await page.locator('#sectionHeading1').fill('记录可见迹象');await page.locator('#sectionBody1').fill('这是用于测试的第一段正文。\n\n这是用于测试的第二段正文。');
    await page.locator('#articleForm [type="submit"]').click();
    await page.locator('#articleDialog').waitFor({state:'hidden'});
    await page.frameLocator('#pagePreview').locator('main h1').filter({hasText:'暴风雨后如何记录屋顶漏水'}).waitFor();
    const english=await browser.newPage();await english.goto(service.origin+'/news',{waitUntil:'networkidle'});assert.equal(await english.locator('main').getByText('暴风雨后如何记录屋顶漏水').count(),0);
    const chinese=await browser.newPage();await chinese.goto(service.origin+'/zh/news',{waitUntil:'networkidle'});assert.equal(await chinese.locator('main').getByText('暴风雨后如何记录屋顶漏水').count(),1);
    for (const preview of [english,chinese]) assert.equal(await preview.locator('a[href^="/__editor"], .adminBtn').count(),0);
    await page.frameLocator('#pagePreview').locator('main img[data-image-source]').first().click();
    await page.locator('#imageForm:not([hidden])').waitFor();
    const imageOptions=await page.locator('#replaceImage option').evaluateAll(nodes=>nodes.map(node=>node.value));
    await page.locator('#replaceImage').selectOption(imageOptions[1]);
    await page.getByRole('button',{name:'编辑文章',exact:true}).click();
    await page.locator('#articleSummary').fill('长'.repeat(1001));
    await page.locator('#articleForm [type="submit"]').click();await page.locator('#articleError').filter({hasText:'摘要'}).waitFor();
    await page.locator('#closeArticle').click();await page.locator('#discardArticle').click();
    assert.match(await page.locator('#saveState').textContent(),/未保存/);assert.ok(await page.locator('#saveButton').isEnabled());
    await page.locator('#saveButton').click();await page.locator('#saveState').filter({hasText:'已保存本地'}).waitFor();
    await page.locator('#historyButton').click();const row=page.locator('.historyRow').filter({hasText:'版本 0'});await row.locator('button').click();await page.locator('#historyDialog').waitFor({state:'hidden'});
    const restored=JSON.parse(await readFile(path.join(directory,'draft.json'),'utf8'));assert.deepEqual(restored.entries,{});assert.equal(restored.articles.length,0);
    await page.setViewportSize({width:390,height:844});assert.ok(await page.locator('#saveButton').isVisible());
    await chinese.goto(service.origin+'/zh/contact',{waitUntil:'networkidle'});await chinese.locator('form button[type="submit"],form button.button').last().click();await chinese.getByText('请输入您的姓名。',{exact:true}).waitFor();
    assert.equal(await chinese.locator('a[href="mailto:elliservices.group@gmail.com"]').count()>0,true);
    assert.deepEqual(errors,[]);
    console.log('Browser flow passed: 120-page directory; Chinese/English; persistent draft; in-flight typing; retry; article guard/create; English isolation; history; mobile; Chinese form errors.');
  } finally {
    await browser?.close();await service?.close();
    if(path.dirname(directory)===tmpdir() && path.basename(directory).startsWith('roof-editor-browser-')) await rm(directory,{recursive:true,force:true});
  }
});
